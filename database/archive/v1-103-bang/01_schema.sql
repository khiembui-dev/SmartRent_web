    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenancy_id uuid NOT NULL REFERENCES tenancies(id),
    billing_period_id uuid REFERENCES billing_periods(id),
    kind varchar(20) NOT NULL CHECK (kind IN ('periodic','final','one_time','replacement','debit_adjustment','credit_adjustment')),
    original_invoice_id uuid REFERENCES invoices(id), code varchar(80) UNIQUE,
    status varchar(8) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','issued','void')),
    service_from date NOT NULL, service_to date NOT NULL,
    issued_on date, due_on date, issued_at timestamptz, issued_by uuid REFERENCES users(id),
    voided_at timestamptz, voided_by uuid REFERENCES users(id), void_reason text, notes text,
    idempotency_key uuid NOT NULL UNIQUE, created_by uuid NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (service_to > service_from), CHECK (due_on IS NULL OR due_on >= issued_on),
    CHECK (id IS DISTINCT FROM original_invoice_id),
