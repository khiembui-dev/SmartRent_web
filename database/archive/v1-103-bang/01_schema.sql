-- SmartRent | PostgreSQL 16+ | UTF-8 | mô hình 3NF
-- Cài một lần vào database mới. Lỗi bất kỳ sẽ rollback toàn bộ file.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA smartrent;
SET LOCAL search_path = smartrent, public;

-- 1. ASP.NET Core Identity (Guid), tài khoản dùng chung giữa các đơn vị.
CREATE TABLE users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_name varchar(256), normalized_user_name varchar(256),
    email varchar(256), normalized_email varchar(256),
    email_confirmed boolean NOT NULL DEFAULT false,
    password_hash text, security_stamp text, concurrency_stamp text,
    phone_number text, phone_number_confirmed boolean NOT NULL DEFAULT false,
    two_factor_enabled boolean NOT NULL DEFAULT false,
    lockout_end timestamptz, lockout_enabled boolean NOT NULL DEFAULT true,
    access_failed_count integer NOT NULL DEFAULT 0 CHECK (access_failed_count >= 0),
    display_name varchar(200) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_name ON users(normalized_user_name) WHERE normalized_user_name IS NOT NULL;
CREATE UNIQUE INDEX ux_users_email ON users(normalized_email) WHERE normalized_email IS NOT NULL;
CREATE TABLE roles (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name varchar(256),
    normalized_name varchar(256), concurrency_stamp text
);
CREATE UNIQUE INDEX ux_roles_name ON roles(normalized_name) WHERE normalized_name IS NOT NULL;
CREATE TABLE user_roles (
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id uuid NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);
CREATE TABLE user_claims (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    claim_type text, claim_value text
);
CREATE TABLE role_claims (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id uuid NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    claim_type text, claim_value text
);
CREATE TABLE user_logins (
    login_provider varchar(128) NOT NULL, provider_key varchar(128) NOT NULL,
    provider_display_name text, user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (login_provider, provider_key)
);
CREATE TABLE user_tokens (
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    login_provider varchar(128) NOT NULL, name varchar(128) NOT NULL, value text,
    PRIMARY KEY (user_id, login_provider, name)
);
CREATE TABLE user_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid NOT NULL REFERENCES users(id),
    refresh_token_hash varchar(128) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL,
    revoked_at timestamptz, replaced_by_id uuid REFERENCES user_sessions(id),
    ip_address inet, user_agent text, CHECK (expires_at > created_at)
);

-- 2. Đơn vị, phân quyền nghiệp vụ và địa chỉ có phiên bản.
CREATE TABLE organizations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), code varchar(40) NOT NULL UNIQUE,
    name varchar(250) NOT NULL, legal_name varchar(250), tax_code varchar(30),
    phone varchar(30), email varchar(256), is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE organization_memberships (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id uuid NOT NULL REFERENCES organizations(id),
    user_id uuid NOT NULL REFERENCES users(id),
    status varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('invited','active','suspended','left')),
    property_scope varchar(10) NOT NULL DEFAULT 'assigned' CHECK (property_scope IN ('all','assigned')),
    joined_at timestamptz NOT NULL DEFAULT now(), UNIQUE (organization_id, user_id)
);
CREATE TABLE permissions (
    code varchar(100) PRIMARY KEY, description text NOT NULL
);
CREATE TABLE business_roles (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    code varchar(50) NOT NULL, name varchar(150) NOT NULL, UNIQUE (organization_id, code)
);
CREATE TABLE business_role_permissions (
    role_id uuid NOT NULL REFERENCES business_roles(id),
    permission_code varchar(100) NOT NULL REFERENCES permissions(code), PRIMARY KEY (role_id, permission_code)
);
CREATE TABLE membership_roles (
    membership_id uuid NOT NULL REFERENCES organization_memberships(id),
    role_id uuid NOT NULL REFERENCES business_roles(id), PRIMARY KEY (membership_id, role_id)
);
CREATE TABLE support_access_grants (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    user_id uuid NOT NULL REFERENCES users(id), granted_by uuid NOT NULL REFERENCES users(id),
    reason text NOT NULL CHECK (btrim(reason) <> ''),
    starts_at timestamptz NOT NULL, expires_at timestamptz NOT NULL, revoked_at timestamptz,
    CHECK (expires_at > starts_at)
);
CREATE TABLE address_datasets (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), code varchar(60) NOT NULL UNIQUE,
    name text NOT NULL, valid_from date NOT NULL, valid_to date, source_url text,
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE TABLE administrative_units (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), dataset_id uuid NOT NULL REFERENCES address_datasets(id),
    parent_id uuid REFERENCES administrative_units(id), code varchar(30) NOT NULL,
    name varchar(200) NOT NULL, unit_level varchar(30) NOT NULL,
    UNIQUE (dataset_id, code), CHECK (id IS DISTINCT FROM parent_id)
);
CREATE TABLE addresses (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    administrative_unit_id uuid REFERENCES administrative_units(id),
    address_line text NOT NULL, manual_locality text,
    latitude numeric(10,7), longitude numeric(10,7),
    CHECK (latitude BETWEEN -90 AND 90), CHECK (longitude BETWEEN -180 AND 180)
);
CREATE TABLE stored_files (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    storage_key text NOT NULL UNIQUE, original_name text NOT NULL, content_type varchar(150) NOT NULL,
    byte_size bigint NOT NULL CHECK (byte_size > 0), sha256 char(64),
    visibility varchar(10) NOT NULL DEFAULT 'private' CHECK (visibility IN ('private','public')),
    scan_status varchar(15) NOT NULL DEFAULT 'pending' CHECK (scan_status IN ('pending','clean','rejected','missing')),
    uploaded_by uuid REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Cơ sở, phòng, tài sản, tin đăng.
CREATE TABLE properties (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    code varchar(40) NOT NULL, name varchar(200) NOT NULL,
    address_id uuid NOT NULL REFERENCES addresses(id), description text,
    contact_name varchar(200), phone varchar(30), email varchar(256),
    is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, code)
);
CREATE TABLE property_billing_settings (
    property_id uuid PRIMARY KEY REFERENCES properties(id),
    invoice_day smallint NOT NULL DEFAULT 1 CHECK (invoice_day BETWEEN 1 AND 31),
    due_after_days smallint NOT NULL DEFAULT 7 CHECK (due_after_days BETWEEN 0 AND 365),
    contract_warning_days smallint NOT NULL DEFAULT 30 CHECK (contract_warning_days >= 0),
    timezone varchar(60) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    proration_policy varchar(20) NOT NULL DEFAULT 'actual_days' CHECK (proration_policy IN ('actual_days','full_month'))
);
CREATE TABLE membership_properties (
    membership_id uuid NOT NULL REFERENCES organization_memberships(id),
    property_id uuid NOT NULL REFERENCES properties(id), PRIMARY KEY (membership_id, property_id)
);
CREATE TABLE room_types (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    code varchar(40) NOT NULL, name varchar(100) NOT NULL, UNIQUE (organization_id, code)
);
CREATE TABLE rooms (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), property_id uuid NOT NULL REFERENCES properties(id),
    room_type_id uuid NOT NULL REFERENCES room_types(id), code varchar(40) NOT NULL, name varchar(150) NOT NULL,
    floor_label varchar(30), area_m2 numeric(8,2) NOT NULL CHECK (area_m2 > 0),
    capacity smallint NOT NULL CHECK (capacity > 0), description text, rules_text text,
    required_deposit numeric(18,0) NOT NULL DEFAULT 0 CHECK (required_deposit >= 0),
    operating_status varchar(15) NOT NULL DEFAULT 'available' CHECK (operating_status IN ('available','maintenance','inactive')),
    created_at timestamptz NOT NULL DEFAULT now(), UNIQUE (property_id, code)
);
CREATE TABLE room_status_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL REFERENCES rooms(id),
    old_status varchar(15), new_status varchar(15) NOT NULL,
    reason text NOT NULL, changed_by uuid REFERENCES users(id), changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE amenities (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    code varchar(50) NOT NULL, name varchar(150) NOT NULL, UNIQUE (organization_id, code)
);
CREATE TABLE room_amenities (
    room_id uuid NOT NULL REFERENCES rooms(id), amenity_id uuid NOT NULL REFERENCES amenities(id),
    PRIMARY KEY (room_id, amenity_id)
);
CREATE TABLE room_images (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL REFERENCES rooms(id),
    file_id uuid NOT NULL REFERENCES stored_files(id), sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_cover boolean NOT NULL DEFAULT false, caption text, UNIQUE (room_id, file_id)
);
CREATE UNIQUE INDEX ux_room_cover ON room_images(room_id) WHERE is_cover;
CREATE TABLE room_assets (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL REFERENCES rooms(id),
    code varchar(50) NOT NULL, name varchar(200) NOT NULL,
    quantity numeric(12,3) NOT NULL CHECK (quantity > 0), condition_notes text,
    acquired_on date, retired_on date, UNIQUE (room_id, code)
);
CREATE TABLE room_listings (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL UNIQUE REFERENCES rooms(id),
    slug varchar(250) NOT NULL UNIQUE, title varchar(250) NOT NULL, description text,
    status varchar(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','hidden')),
    published_at timestamptz, updated_at timestamptz NOT NULL DEFAULT now()
);

-- 4. Khách, giấy tờ, yêu cầu, giữ chỗ. Hồ sơ khách thuộc một đơn vị; tài khoản là tùy chọn.
CREATE TABLE tenants (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    user_id uuid REFERENCES users(id), code varchar(40) NOT NULL, full_name varchar(200) NOT NULL,
    email varchar(256), phone varchar(30), date_of_birth date,
    address_id uuid REFERENCES addresses(id), emergency_contact_name varchar(200), emergency_contact_phone varchar(30),
    notes text, created_at timestamptz NOT NULL DEFAULT now(), UNIQUE (organization_id, code)
);
CREATE UNIQUE INDEX ux_tenant_account ON tenants(organization_id, user_id) WHERE user_id IS NOT NULL;
CREATE INDEX ix_tenant_email ON tenants(organization_id, lower(email));
CREATE INDEX ix_tenant_phone ON tenants(organization_id, phone);
CREATE TABLE tenant_identity_documents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenant_id uuid NOT NULL REFERENCES tenants(id),
    document_type varchar(30) NOT NULL, number_ciphertext bytea NOT NULL, number_fingerprint varchar(128) NOT NULL,
    issued_on date, issuing_authority text, expires_on date,
    front_file_id uuid REFERENCES stored_files(id), back_file_id uuid REFERENCES stored_files(id),
    verified_by uuid REFERENCES users(id), verified_at timestamptz,
    CHECK ((verified_by IS NULL) = (verified_at IS NULL)), UNIQUE (tenant_id, document_type, number_fingerprint)
);
CREATE TABLE tenant_profile_change_requests (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenant_id uuid NOT NULL REFERENCES tenants(id),
    requested_by uuid NOT NULL REFERENCES users(id), requested_at timestamptz NOT NULL DEFAULT now(),
    status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled')),
    proposed_full_name varchar(200), proposed_phone varchar(30), proposed_email varchar(256),
    proposed_address_id uuid REFERENCES addresses(id), reason text, reviewed_by uuid REFERENCES users(id), reviewed_at timestamptz
);
CREATE TABLE rental_inquiries (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL REFERENCES rooms(id),
    contact_name varchar(200) NOT NULL, phone varchar(30), email varchar(256),
    desired_move_in date, occupants smallint NOT NULL DEFAULT 1 CHECK (occupants > 0), message text,
    status varchar(15) NOT NULL DEFAULT 'new' CHECK (status IN ('new','accepted','consulting','viewing','approved','rejected','cancelled','converted')),
    assigned_to uuid REFERENCES users(id), tenant_id uuid REFERENCES tenants(id),
    closed_reason text, created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (nullif(btrim(phone),'') IS NOT NULL OR nullif(btrim(email),'') IS NOT NULL)
);
CREATE TABLE inquiry_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), inquiry_id uuid NOT NULL REFERENCES rental_inquiries(id),
    event_type varchar(40) NOT NULL, notes text NOT NULL, actor_id uuid REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE room_viewings (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), inquiry_id uuid NOT NULL REFERENCES rental_inquiries(id),
    starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL, host_user_id uuid REFERENCES users(id),
    status varchar(12) NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','completed','cancelled','no_show')),
    result_notes text, CHECK (ends_at > starts_at)
);
-- Lịch chiếm dụng chung cho cả giữ chỗ và thuê: một EXCLUDE bảo vệ cả hai luồng.
CREATE TABLE room_allocations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL REFERENCES rooms(id),
    starts_on date NOT NULL, ends_on date,
    state varchar(12) NOT NULL CHECK (state IN ('held','reserved','occupied','completed','released')),
    hold_expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (ends_on IS NULL OR ends_on > starts_on),
    CHECK (state <> 'held' OR (hold_expires_at IS NOT NULL AND ends_on IS NOT NULL)),
    CHECK (state <> 'completed' OR ends_on IS NOT NULL),
    EXCLUDE USING gist (room_id WITH =, daterange(starts_on, ends_on, '[)') WITH &&)
        WHERE (state IN ('held','reserved','occupied','completed'))
);
CREATE TABLE reservations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), inquiry_id uuid REFERENCES rental_inquiries(id),
    allocation_id uuid NOT NULL UNIQUE REFERENCES room_allocations(id), tenant_id uuid NOT NULL REFERENCES tenants(id),
    status varchar(12) NOT NULL DEFAULT 'holding' CHECK (status IN ('holding','converted','expired','cancelled')),
    cancellation_terms text NOT NULL, cancelled_reason text,
    handled_by uuid NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now()
);

-- 5. Đợt thuê và tài liệu hợp đồng. Phòng được suy qua allocation, không sao chép.
CREATE TABLE tenancies (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), allocation_id uuid NOT NULL UNIQUE REFERENCES room_allocations(id),
    representative_tenant_id uuid NOT NULL REFERENCES tenants(id), reservation_id uuid UNIQUE REFERENCES reservations(id),
    status varchar(12) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','active','ended','cancelled')),
    planned_move_in date NOT NULL, actual_move_in date, actual_move_out date,
    onboarding_mode varchar(10) NOT NULL DEFAULT 'normal' CHECK (onboarding_mode IN ('normal','import')),
    end_reason text, ended_by uuid REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (actual_move_out IS NULL OR (actual_move_in IS NOT NULL AND actual_move_out > actual_move_in)),
    CHECK (status NOT IN ('active','ended') OR actual_move_in IS NOT NULL),
    CHECK (status <> 'ended' OR (actual_move_out IS NOT NULL AND ended_by IS NOT NULL AND nullif(btrim(end_reason),'') IS NOT NULL)),
    CHECK (status <> 'active' OR actual_move_out IS NULL),
    CHECK (status NOT IN ('planned','cancelled') OR (actual_move_in IS NULL AND actual_move_out IS NULL))
);
CREATE UNIQUE INDEX ux_representative_active ON tenancies(representative_tenant_id) WHERE status IN ('planned','active');
CREATE TABLE tenancy_residents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenancy_id uuid NOT NULL REFERENCES tenancies(id),
    tenant_id uuid NOT NULL REFERENCES tenants(id), joined_on date NOT NULL, left_on date,
    relationship varchar(100), CHECK (left_on IS NULL OR left_on > joined_on),
    EXCLUDE USING gist (tenancy_id WITH =, tenant_id WITH =, daterange(joined_on,left_on,'[)') WITH &&)
);
CREATE TABLE onboarding_gaps (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenancy_id uuid NOT NULL REFERENCES tenancies(id),
    missing_item varchar(100) NOT NULL, source_reference text, notes text,
    resolved_at timestamptz, resolved_by uuid REFERENCES users(id), UNIQUE (tenancy_id, missing_item)
);
CREATE TABLE contracts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenancy_id uuid NOT NULL REFERENCES tenancies(id),
    code varchar(80) NOT NULL UNIQUE, predecessor_contract_id uuid REFERENCES contracts(id),
    archived_at timestamptz, created_by uuid NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (id IS DISTINCT FROM predecessor_contract_id)
);
CREATE TABLE contract_versions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), contract_id uuid NOT NULL REFERENCES contracts(id),
    version_no integer NOT NULL CHECK (version_no > 0), effective_from date NOT NULL, ends_on date NOT NULL,
    required_deposit numeric(18,0) NOT NULL CHECK (required_deposit >= 0),
    invoice_day smallint NOT NULL CHECK (invoice_day BETWEEN 1 AND 31),
    due_after_days smallint NOT NULL CHECK (due_after_days BETWEEN 0 AND 365),
    proration_policy varchar(20) NOT NULL CHECK (proration_policy IN ('actual_days','full_month')),
    terms_text text NOT NULL, change_reason text,
    signed_at timestamptz, confirmed_by uuid REFERENCES users(id),
    signature_method varchar(15) CHECK (signature_method IN ('paper','external_esign')),
    external_signature_reference text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (contract_id, version_no), UNIQUE (contract_id, effective_from), CHECK (ends_on > effective_from),
    CHECK ((signed_at IS NULL AND confirmed_by IS NULL AND signature_method IS NULL)
        OR (signed_at IS NOT NULL AND confirmed_by IS NOT NULL AND signature_method IS NOT NULL))
);
CREATE TABLE contract_parties (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), contract_version_id uuid NOT NULL REFERENCES contract_versions(id),
    party_role varchar(20) NOT NULL CHECK (party_role IN ('landlord','representative','co_signer')),
    full_name_snapshot varchar(250) NOT NULL, address_snapshot text NOT NULL,
    identity_ciphertext bytea, contact_snapshot text, tenant_id uuid REFERENCES tenants(id)
);
CREATE TABLE contract_files (
    contract_version_id uuid NOT NULL REFERENCES contract_versions(id), file_id uuid NOT NULL REFERENCES stored_files(id),
    file_kind varchar(20) NOT NULL CHECK (file_kind IN ('draft','signed','appendix','signature_proof')),
    PRIMARY KEY (contract_version_id, file_id)
);
CREATE TABLE contract_terminations (
    contract_id uuid PRIMARY KEY REFERENCES contracts(id), ends_on date NOT NULL,
    reason text NOT NULL, confirmed_by uuid NOT NULL REFERENCES users(id), confirmed_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE tenancy_requests (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenancy_id uuid NOT NULL REFERENCES tenancies(id),
    request_type varchar(12) NOT NULL CHECK (request_type IN ('renewal','transfer','checkout')),
    desired_on date NOT NULL, target_room_id uuid REFERENCES rooms(id), message text,
    status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled','completed')),
    requested_by uuid NOT NULL REFERENCES users(id), reviewed_by uuid REFERENCES users(id), decision_notes text,
    created_at timestamptz NOT NULL DEFAULT now(), reviewed_at timestamptz,
    CHECK ((request_type = 'transfer') = (target_room_id IS NOT NULL))
);
CREATE TABLE room_transfers (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), old_tenancy_id uuid NOT NULL UNIQUE REFERENCES tenancies(id),
    new_tenancy_id uuid NOT NULL UNIQUE REFERENCES tenancies(id), transfer_on date NOT NULL,
    reason text NOT NULL, confirmed_by uuid NOT NULL REFERENCES users(id), confirmed_at timestamptz NOT NULL DEFAULT now(),
    CHECK (old_tenancy_id <> new_tenancy_id)
);

-- 6. Giá: cơ sở -> phòng -> phiên bản hợp đồng. Không dùng số 0 làm "chưa có".
CREATE TABLE charge_types (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), organization_id uuid NOT NULL REFERENCES organizations(id),
    code varchar(50) NOT NULL, name varchar(200) NOT NULL,
    category varchar(20) NOT NULL CHECK (category IN ('rent','electricity','water','service','other','compensation')),
    unit_label varchar(30) NOT NULL, is_active boolean NOT NULL DEFAULT true, UNIQUE (organization_id, code)
);
CREATE TABLE rate_plans (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), property_id uuid UNIQUE REFERENCES properties(id),
    room_id uuid UNIQUE REFERENCES rooms(id), contract_version_id uuid UNIQUE REFERENCES contract_versions(id),
    CHECK (num_nonnulls(property_id, room_id, contract_version_id) = 1)
);
CREATE TABLE charge_rates (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), rate_plan_id uuid NOT NULL REFERENCES rate_plans(id),
    charge_type_id uuid NOT NULL REFERENCES charge_types(id), effective_from date NOT NULL, effective_to date,
    unit_price numeric(18,4) NOT NULL CHECK (unit_price >= 0),
    calculation_method varchar(15) NOT NULL CHECK (calculation_method IN ('fixed','metered','per_person','per_quantity')),
    billing_cycle varchar(10) NOT NULL CHECK (billing_cycle IN ('monthly','once')),
    proration_mode varchar(12) NOT NULL DEFAULT 'full_period' CHECK (proration_mode IN ('full_period','actual_days')),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    EXCLUDE USING gist (rate_plan_id WITH =, charge_type_id WITH =, daterange(effective_from,effective_to,'[)') WITH &&)
);

-- 7. Kỳ, bàn giao, công tơ và các lần ghi bất biến.
CREATE TABLE billing_periods (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), property_id uuid NOT NULL REFERENCES properties(id),
    month_start date NOT NULL CHECK (extract(day FROM month_start) = 1),
    status varchar(8) NOT NULL DEFAULT 'open' CHECK (status IN ('open','locked')),
    locked_at timestamptz, locked_by uuid REFERENCES users(id), UNIQUE (property_id, month_start),
    CHECK ((status = 'locked' AND locked_at IS NOT NULL AND locked_by IS NOT NULL)
       OR (status = 'open' AND locked_at IS NULL AND locked_by IS NULL))
);
CREATE TABLE billing_period_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), billing_period_id uuid NOT NULL REFERENCES billing_periods(id),
    action varchar(8) NOT NULL CHECK (action IN ('lock','unlock')),
    reason text NOT NULL CHECK (btrim(reason) <> ''), actor_id uuid NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE handovers (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tenancy_id uuid NOT NULL REFERENCES tenancies(id),
    kind varchar(15) NOT NULL CHECK (kind IN ('checkin','checkout','transfer_in','transfer_out')),
    occurred_at timestamptz NOT NULL, notes text, landlord_confirmed_by uuid REFERENCES users(id),
    tenant_confirmed_by uuid REFERENCES users(id), confirmed_at timestamptz,
    representative_confirmation_text text
);
CREATE TABLE handover_assets (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), handover_id uuid NOT NULL REFERENCES handovers(id),
    room_asset_id uuid NOT NULL REFERENCES room_assets(id), name_snapshot text NOT NULL,
    quantity numeric(12,3) NOT NULL CHECK (quantity >= 0), condition_notes text NOT NULL,
    UNIQUE (handover_id, room_asset_id)
);
CREATE TABLE handover_files (
    handover_id uuid NOT NULL REFERENCES handovers(id), file_id uuid NOT NULL REFERENCES stored_files(id),
    PRIMARY KEY (handover_id, file_id)
);
CREATE TABLE meters (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), room_id uuid NOT NULL REFERENCES rooms(id),
    meter_kind varchar(12) NOT NULL CHECK (meter_kind IN ('electricity','water')),
    serial_number varchar(100) NOT NULL, installed_at timestamptz NOT NULL, removed_at timestamptz,
    CHECK (removed_at IS NULL OR removed_at > installed_at),
