-- PostgreSQL không tự tạo index phía FK. Bổ sung index cho mọi FK chưa có tiền tố index.
DO $$
DECLARE r record; col_name text;
BEGIN
  FOR r IN SELECT c.conrelid, c.conkey[1] AS attnum, t.relname
           FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
           JOIN pg_namespace n ON n.oid=t.relnamespace
           WHERE c.contype='f' AND n.nspname='smartrent' AND array_length(c.conkey,1)=1
  LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid=r.conrelid
                   AND i.indkey[0]=r.attnum AND i.indpred IS NULL) THEN
      SELECT attname INTO col_name FROM pg_attribute WHERE attrelid=r.conrelid AND attnum=r.attnum;
      EXECUTE format('CREATE INDEX %I ON smartrent.%I (%I)', 'ix_'||r.relname||'_'||col_name,r.relname,col_name);
    END IF;
  END LOOP;
END $$;
